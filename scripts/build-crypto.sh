#!/bin/bash
# Adapted from bindings/apple/build_crypto_xcframework.sh at the pinned commit.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BASE="${MOOD_TOOLCHAINS:-$HOME/mood-toolchains}"
export RUSTUP_HOME="$BASE/rustup" CARGO_HOME="$BASE/cargo"
export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
export PATH="$CARGO_HOME/bin:$PATH" RUSTUP_TOOLCHAIN=1.93.0
TAG=matrix-sdk-crypto-ffi-0.17.0
COMMIT=cf099deb272f2ef44a0b8b8f7afd96004c3a822a
SRC="$BASE/matrix-rust-sdk"
if [ ! -d "$SRC/.git" ]; then
  git clone --depth 1 --branch "$TAG" https://github.com/matrix-org/matrix-rust-sdk.git "$SRC"
fi
[ "$(git -C "$SRC" rev-parse HEAD)" = "$COMMIT" ] || { echo 'Unexpected source commit' >&2; exit 1; }
PATCH="$ROOT/mood/Vendor/MatrixSDKCrypto/memory-store.patch"
if [ -z "$(git -C "$SRC" status --porcelain)" ]; then git -C "$SRC" apply "$PATCH"; fi
[ -z "$(git -C "$SRC" ls-files --others --exclude-standard)" ] || { echo 'Untracked SDK files' >&2; exit 1; }
git -C "$SRC" diff --binary | cmp - "$PATCH" || { echo 'Unexpected SDK source modifications' >&2; exit 1; }
rustup toolchain install 1.93.0 --profile minimal
rustup target add aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-ios-macabi
export CARGO_TARGET_DIR="$BASE/crypto-target"
export IPHONEOS_DEPLOYMENT_TARGET=17.0
cd "$SRC"
for target in aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-ios-macabi; do
  cargo build --locked --release -p matrix-sdk-crypto-ffi --target "$target"
done
GEN="$BASE/crypto-generated"
mkdir -p "$GEN/headers"
cargo run --locked --release -p matrix-sdk-crypto-ffi --bin matrix_sdk_crypto_ffi -- generate --language swift \
  --library "$CARGO_TARGET_DIR/aarch64-apple-ios/release/libmatrix_sdk_crypto_ffi.a" --out-dir "$GEN"
find "$GEN" -maxdepth 1 -name '*.h' -exec cp {} "$GEN/headers/" \;
# Fixed order keeps the expected modulemap hash independent of directory enumeration.
for module in matrix_sdk_cryptoFFI MatrixSDKCryptoFFI matrix_sdk_commonFFI; do
  cat "$GEN/$module.modulemap"
done > "$GEN/headers/module.modulemap"
OUT="$ROOT/mood/Vendor/MatrixSDKCrypto"
# Only replace generated output after all Rust builds have succeeded.
rm -rf "$OUT/MatrixSDKCrypto.xcframework"
xcodebuild -create-xcframework \
  -library "$CARGO_TARGET_DIR/aarch64-apple-ios/release/libmatrix_sdk_crypto_ffi.a" -headers "$GEN/headers" \
  -library "$CARGO_TARGET_DIR/aarch64-apple-ios-sim/release/libmatrix_sdk_crypto_ffi.a" -headers "$GEN/headers" \
  -library "$CARGO_TARGET_DIR/aarch64-apple-ios-macabi/release/libmatrix_sdk_crypto_ffi.a" -headers "$GEN/headers" \
  -output "$OUT/MatrixSDKCrypto.xcframework"
find "$GEN" -maxdepth 1 -name '*.swift' -exec cp {} "$OUT/" \;
# UniFFI shares C buffer types across the three modules. Swift's enabled
# MemberImportVisibility requires all defining FFI modules in each generated file.
python3 - "$OUT" <<'PYIMPORTS'
import sys
from pathlib import Path
shim = "// Explicit FFI imports for Swift MemberImportVisibility (generated by build-crypto.sh).\nimport MatrixSDKCryptoFFI\nimport matrix_sdk_commonFFI\nimport matrix_sdk_cryptoFFI\n\n"
for source in Path(sys.argv[1]).glob("*.swift"):
    source.write_text(shim + source.read_text())
PYIMPORTS
cp "$SRC/LICENSE" "$OUT/LICENSE"
cd "$OUT"
find MatrixSDKCrypto.xcframework -type f -exec shasum -a 256 {} \; | LC_ALL=C sort > SHA256SUMS.generated
if [ -f SHA256SUMS ]; then diff -u SHA256SUMS SHA256SUMS.generated; fi
